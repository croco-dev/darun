import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const packageDirectory = fileURLToPath(new URL('../libs/shared/provider-graphql/', import.meta.url));

test('check-only generation detects source and output drift without writing repository files', () => {
  const root = mkdtempSync(join(tmpdir(), 'darun-codegen-fixture-'));
  const directory = join(root, 'libs/shared/provider-graphql');
  const generatedDirectory = join(root, 'libs/__generated__');
  const temporaryDirectory = join(root, 'temporary');
  const schema = join(root, 'apps/graphql-api/schema.graphql');
  const sourcePaths = [
    'libs/example/feature/src/query.ts',
    'apps/admin-web/features/query.ts',
    'apps/service-web/features/query.tsx',
    'apps/visual-web/features/query.ts',
  ];
  const snapshot = () =>
    Object.fromEntries(
      readdirSync(generatedDirectory).map(file => [file, readFileSync(join(generatedDirectory, file))])
    );
  const run = args => {
    const result = spawnSync(process.execPath, args, {
      cwd: directory,
      env: { ...process.env, TMPDIR: temporaryDirectory, TMP: temporaryDirectory, TEMP: temporaryDirectory },
      encoding: 'utf8',
      timeout: 60_000,
    });
    assert.ifError(result.error);
    return { status: result.status, output: `${result.stdout}${result.stderr}` };
  };
  const generate = () => {
    const result = run(['node_modules/@graphql-codegen/cli/cjs/bin.js', '--config', './codegen.ts']);
    assert.equal(result.status, 0, result.output);
  };
  const check = expectedStatus => {
    const before = snapshot();
    const result = run(['scripts/check-codegen.mjs']);
    assert.equal(result.status, expectedStatus, result.output);
    assert.deepEqual(snapshot(), before, 'check-only must preserve every generated byte, including stale files');
    assert.deepEqual(
      readdirSync(temporaryDirectory).filter(name => name.startsWith('darun-codegen-check-')),
      [],
      'temporary outputs must be removed on success and failure'
    );
    if (expectedStatus === 1) {
      assert.match(result.output, /libs[/\\]__generated__[/\\]/);
      assert.match(result.output, /pnpm --filter @darun\/provider-graphql codegen/);
    }
    return result;
  };

  try {
    mkdirSync(join(directory, 'scripts'), { recursive: true });
    mkdirSync(temporaryDirectory);
    mkdirSync(join(root, 'apps/graphql-api'), { recursive: true });
    writeFileSync(join(directory, 'package.json'), '{"type":"module"}');
    cpSync(join(packageDirectory, 'codegen.ts'), join(directory, 'codegen.ts'));
    cpSync(join(packageDirectory, 'scripts/check-codegen.mjs'), join(directory, 'scripts/check-codegen.mjs'));
    symlinkSync(join(packageDirectory, 'node_modules'), join(directory, 'node_modules'), 'dir');
    writeFileSync(schema, 'type Query { health: String! }');
    sourcePaths.forEach((file, index) => {
      mkdirSync(join(root, file, '..'), { recursive: true });
      // Static plucking must not execute application modules.
      writeFileSync(join(root, file), `throw new Error('must not execute');\ngql\`query Probe${index} { health }\`;`);
    });
    generate();
    check(0);

    for (const [index, file] of sourcePaths.entries()) {
      writeFileSync(join(root, file), `gql\`query Probe${index} { renamedHealth: health }\`;`);
      check(1);
      generate();
      check(0);
    }
    writeFileSync(schema, 'type Query { health: String }');
    check(1);
    generate();
    check(0);

    rmSync(join(generatedDirectory, 'gql.ts'));
    assert.match(check(1).output, /gql\.ts/);
    generate();
    mkdirSync(join(generatedDirectory, 'obsolete'));
    writeFileSync(join(generatedDirectory, 'obsolete/old.ts'), 'export const obsolete = true;');
    const before = readFileSync(join(generatedDirectory, 'obsolete/old.ts'));
    const failed = run(['scripts/check-codegen.mjs']);
    assert.equal(failed.status, 1, failed.output);
    assert.match(failed.output, /obsolete[/\\]old\.ts/);
    assert.deepEqual(readFileSync(join(generatedDirectory, 'obsolete/old.ts')), before);
    rmSync(join(generatedDirectory, 'obsolete'), { recursive: true });

    const original = snapshot();
    writeFileSync(join(root, sourcePaths[0]), 'gql`query Invalid { unknownField }`;');
    const invalid = run(['scripts/check-codegen.mjs']);
    assert.equal(invalid.status, 1, invalid.output);
    assert.match(invalid.output, /unknownField/);
    assert.deepEqual(snapshot(), original);
    assert.deepEqual(
      readdirSync(temporaryDirectory).filter(name => name.startsWith('darun-codegen-check-')),
      []
    );
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
